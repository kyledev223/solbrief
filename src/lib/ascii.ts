/** Pixel matrix (true = filled) for a string, with 1px letter spacing. */
export function pixelMatrix(text: string): boolean[][] {
  const rows: boolean[][] = Array.from({ length: 7 }, () => []);
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = (G[ch] ?? G[" "]).split("|");
    glyph.forEach((line, r) => {
      if (i > 0) rows[r].push(false);
      for (const c of line) rows[r].push(c === "#");
    });
  });
  return rows;
}

export function asciiLogo(text: string, { fill = "██", shade = "░░", empty = "  " } = {}): string {
  const m = pixelMatrix(text);
  const h = m.length + 1;
  const w = (m[0]?.length ?? 0) + 1;
  const at = (r: number, c: number) => r >= 0 && r < m.length && c >= 0 && c < (m[0]?.length ?? 0) && m[r][c];
  const lines: string[] = [];
  for (let r = 0; r < h; r++) {
    let line = "";
    for (let c = 0; c < w; c++) line += at(r, c) ? fill : at(r - 1, c - 1) ? shade : empty;
    lines.push(line.replace(/\s+$/, ""));
  }
  return lines.join("\n");
}
